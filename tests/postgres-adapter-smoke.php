<?php
declare(strict_types=1);

/**
 * Smoke test do adaptador MySQLi/PDO contra PostgreSQL temporário.
 * Executado apenas no GitHub Actions; usa TEMP TABLE e não altera dados persistentes.
 */
require_once "/var/www/html/conexao.php";

function garantir(bool $condicao, string $mensagem): void
{
    if (!$condicao) {
        throw new RuntimeException($mensagem);
    }
}

$pdo = $conexao->pdo;
$pdo->exec("
    CREATE TEMPORARY TABLE devolucoes (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        descricao TEXT NOT NULL UNIQUE
    ) ON COMMIT PRESERVE ROWS
");

$descricao = "teste-adaptador-" . bin2hex(random_bytes(4));
$stmt = $conexao->prepare("INSERT INTO devolucoes (descricao) VALUES (?)");
garantir($stmt instanceof mysqli_stmt, "prepare() não retornou mysqli_stmt.");
$stmt->bind_param("s", $descricao);
garantir($stmt->execute(), "INSERT com bind_param/execute falhou.");
$novoId = $conexao->insert_id;
garantir($novoId > 0, "RETURNING id não preencheu insert_id.");
$stmt->close();

$stmt = $conexao->prepare("SELECT id, descricao FROM devolucoes WHERE id = ?");
$id = $novoId;
$stmt->bind_param("i", $id);
garantir($stmt->execute(), "SELECT preparado falhou.");
$resultado = $stmt->get_result();
$linha = $resultado->fetch_assoc();
garantir(($linha["descricao"] ?? null) === $descricao, "get_result()/fetch_assoc() retornou dados incorretos.");
garantir($resultado->num_rows === 1, "num_rows deveria ser 1.");
$stmt->close();

$conexao->begin_transaction();
$descricaoRollback = "rollback-" . bin2hex(random_bytes(4));
$stmt = $conexao->prepare("INSERT INTO devolucoes (descricao) VALUES (?)");
$stmt->bind_param("s", $descricaoRollback);
garantir($stmt->execute(), "INSERT dentro da transação falhou.");
$stmt->close();
garantir($conexao->rollback(), "rollback() falhou.");

$resultado = $conexao->query("SELECT id, descricao FROM devolucoes ORDER BY id");
garantir($resultado instanceof mysqli_result, "query() não retornou mysqli_result.");
$linhas = $resultado->fetch_all(MYSQLI_ASSOC);
garantir(count($linhas) === 1, "rollback não desfez a inserção temporária.");
garantir($linhas[0]["descricao"] === $descricao, "fetch_all() retornou conteúdo incorreto.");

$duplicado = $conexao->prepare("INSERT INTO devolucoes (descricao) VALUES (?)");
$duplicado->bind_param("s", $descricao);
garantir(!$duplicado->execute(), "Restrição UNIQUE não foi aplicada.");
garantir($duplicado->errno === 1062, "Erro de duplicidade não foi mapeado para errno 1062.");
$duplicado->close();

echo "OK: conexão PDO_PGSQL, bind_param, execute, RETURNING/insert_id, get_result, fetch_assoc, fetch_all, query, transação/rollback e duplicidade.\n";
